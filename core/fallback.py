def reply(emotion_label: str, scene: str) -> str:
    """按情绪 + 场景选一条。轮换使用，避免连续两条一样。"""
    if emotion_label == "消极":
        pool = REPLIES["消极"].get(scene) or REPLIES["消极"]["general"]
    elif emotion_label == "积极":
        pool = REPLIES["积极"]
    else:
        pool = REPLIES["中性"]

    n = _round["n"]
    _round["n"] = (n + 1) % 997
    return pool[n % len(pool)]


