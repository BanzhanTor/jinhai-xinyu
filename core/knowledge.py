def list_articles(cat: str = "全部", keyword: str = "") -> list[dict]:
    """按分类 + 关键词筛选，返回不含正文的列表项。"""
    kw = (keyword or "").strip()
    out = []
    for a in ARTICLES:
        if cat and cat != "全部" and a["cat"] != cat:
            continue
        if kw and kw not in (a["title"] + a["summary"] + "".join(a["body"])):
            continue
        out.append({
            "id": a["id"], "cat": a["cat"], "minutes": a["minutes"],
            "title": a["title"], "summary": a["summary"],
        })
    return out


def get_article(aid: int) -> dict | None:
    for a in ARTICLES:
        if a["id"] == aid:
            return dict(a)
    return None
